def test_a_changed_world_invalidates_an_approved_plan(seeded, ari, noor) -> None:
    """Move B09 back to South after approval: five batches, 400 cents, equal."""
    helpers.apply_correction(ari)
    plan = helpers.staged_plan(ari)
    assert helpers.approve(noor, plan).status_code == 200

    graph = seeded["graph"]
    graph.run(
        """
        MATCH (b:Batch {id:'B09'})-[a:ASSIGNED_TO]->(:Lane)
        MATCH (south:Lane {id:$south})
        DELETE a
        CREATE (b)-[:ASSIGNED_TO]->(south)
        """,
        {"south": domain.LANE_SOUTH},
    )

    refused = helpers.release(noor, plan["plan_id"])
    assert refused.status_code == 409
    assert refused.json()["code"] == "STALE_PLAN"

    state = helpers.workspace(ari)
    assert state["comparison"]["right"]["batch_count"] == 5
    assert state["comparison"]["right"]["mean_display_cents"] == 400
    assert state["comparison"]["relation"] == domain.RELATION_EQUAL
    assert state["current_release"]["release_id"] == seeded["version_one"]["release_id"]


def test_the_full_release_issues_both_editions_as_one_package(seeded, ari, noor) -> None:
    helpers.apply_correction(ari)
    plan = helpers.staged_plan(ari)
    assert helpers.approve(noor, plan).status_code == 200

    issued = helpers.release(noor, plan["plan_id"])
    assert issued.status_code == 200, issued.text
    body = issued.json()
    assert body["idempotent"] is False
    assert body["verification"]["ok"] is True

    released = body["release"]
    assert sorted(released["document_ids"]) == sorted([domain.DOC_OPS, domain.DOC_MEMO])

    state = helpers.workspace(ari)
    assert state["current_release"]["release_id"] == released["release_id"]
    assert state["decision"]["status"] == "RETURNED_FOR_REVIEW"

    # The issued bytes, served from the committed release.
    ops = ari.get(f"/editions/{released['release_id']}/{domain.DOC_OPS}")
    memo = ari.get(f"/editions/{released['release_id']}/{domain.DOC_MEMO}")
    assert ops.status_code == 200 and memo.status_code == 200
    assert "South costs $0.40 more per parcel than North." in ops.text
    assert "South is 40 cents more expensive per parcel than North." in memo.text
    assert "cheaper" not in memo.text
    assert 'data-decision-status="RETURNED_FOR_REVIEW"' in memo.text

    # Version 1 remains readable and immutable.
    old = ari.get(f"/editions/{seeded['version_one']['release_id']}/{domain.DOC_OPS}")
    assert "South costs $0.40 less per parcel than North." in old.text

    artifacts = json.loads(released["artifacts"])
    assert hashlib.sha256(ops.content).hexdigest() == artifacts[domain.DOC_OPS]["sha256"]
    assert hashlib.sha256(memo.content).hexdigest() == artifacts[domain.DOC_MEMO]["sha256"]


def test_a_repeated_release_is_idempotent(seeded, ari, noor) -> None:
    helpers.apply_correction(ari)
    plan = helpers.staged_plan(ari)
    helpers.approve(noor, plan)

    first = helpers.release(noor, plan["plan_id"], operation_id="op-retry")
    second = helpers.release(noor, plan["plan_id"], operation_id="op-retry")
    assert first.status_code == 200 and second.status_code == 200
    assert second.json()["idempotent"] is True
    assert second.json()["release"]["release_id"] == first.json()["release"]["release_id"]

    history = helpers.workspace(ari)["releases"]
    assert len(history) == 2  # Version 1 plus this one, not three.


