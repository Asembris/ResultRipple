def test_correction_changes_exactly_three_memberships_and_no_measurement(
    seeded, ari: TestClient
) -> None:
    before = helpers.workspace(ari)
    raw_sha_before = before["evidence"]["dataset_sha"]
    costs_before = {b["batch_id"]: b["cost_cents"] for b in before["evidence"]["batches"]}
    lanes_before = {b["batch_id"]: b["lane_id"] for b in before["evidence"]["batches"]}

    applied = helpers.apply_correction(ari)
    assert applied["applied_edge_count"] == 3
    assert applied["context_revision"] == before["context_revision"] + 1

    after = helpers.workspace(ari)
    costs_after = {b["batch_id"]: b["cost_cents"] for b in after["evidence"]["batches"]}
    lanes_after = {b["batch_id"]: b["lane_id"] for b in after["evidence"]["batches"]}

    # The raw file and every recorded cost are untouched.
    assert after["evidence"]["dataset_sha"] == raw_sha_before
    assert costs_after == costs_before
    assert hashlib.sha256(seeded["csv_path"].read_bytes()).hexdigest() == raw_sha_before

    changed = {b for b in lanes_before if lanes_before[b] != lanes_after[b]}
    assert changed == {"B09", "B10", "B11"}
    assert all(lanes_after[b] == domain.LANE_PILOT for b in changed)

    # North 400 unchanged; South 360 -> 440; +40 becomes -40.
    assert after["comparison"]["left"]["mean_display_cents"] == 400
    assert after["comparison"]["right"]["mean_display_cents"] == 440
    assert after["comparison"]["right"]["batch_count"] == 4
    assert after["comparison"]["relation"] == domain.RELATION_HIGHER
    assert after["comparison"]["magnitude_cents"] == 40


