"""Independent artifact verification.

This module deliberately imports nothing from the engine, the renderer, the
templates, or the domain constants. It re-reads the immutable CSV and the
captured effective-membership snapshot, re-derives the arithmetic with its own
`Fraction` code, re-states the expected sentence with its own copy of the
permitted grammar, and parses the actual generated bytes with `HTMLParser`.

Agreement between two independent implementations is the point. "Gate cleared"
is not evidence, and a file hash proves which bytes were issued -- not that the
dispatch note or the approved provenance is true in the real world.
"""

from __future__ import annotations

import csv
import hashlib
from dataclasses import dataclass, field
from fractions import Fraction
from html.parser import HTMLParser
from pathlib import Path
from typing import Any

# -- parsed document ----------------------------------------------------------


@dataclass
class ParsedBlock:
    block_id: str
    kind: str
    attrs: dict[str, str]
    paragraphs: list[str] = field(default_factory=list)


class _DocumentParser(HTMLParser):
    """Collect every block section, its data attributes, and its paragraphs."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.blocks: list[ParsedBlock] = []
        self.meta: dict[str, str] = {}
        self._depth = 0
        self._current: ParsedBlock | None = None
        self._in_paragraph = False
        self._buffer: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        attributes = {key: (value or "") for key, value in attrs}
        if tag == "meta" and attributes.get("name", "").startswith("rr-"):
            self.meta[attributes["name"]] = attributes.get("content", "")
        if tag == "section" and "data-block-kind" in attributes:
            self._current = ParsedBlock(
                block_id=attributes.get("id", ""),
                kind=attributes["data-block-kind"],
                attrs=attributes,
            )
            self._depth = 1
            return
        if self._current is not None:
            if tag == "section":
                self._depth += 1
            if tag == "p":
                self._in_paragraph = True
                self._buffer = []

    def handle_endtag(self, tag: str) -> None:
        if self._current is None:
            return
        if tag == "p" and self._in_paragraph:
            self._current.paragraphs.append(" ".join("".join(self._buffer).split()))
            self._in_paragraph = False
            self._buffer = []
        elif tag == "section":
            self._depth -= 1
            if self._depth == 0:
                self.blocks.append(self._current)
                self._current = None

    def handle_data(self, data: str) -> None:
        if self._in_paragraph:
            self._buffer.append(data)


def parse_document(body: bytes) -> tuple[list[ParsedBlock], dict[str, str]]:
    parser = _DocumentParser()
    parser.feed(body.decode("utf-8"))
    parser.close()
    return parser.blocks, parser.meta


# -- independent arithmetic ---------------------------------------------------


def _round_half_up(value: Fraction) -> int:
    if value >= 0:
        return int((value * 2 + 1) // 2)
    return -int(((-value) * 2 + 1) // 2)


def _money(cents: int) -> str:
    return f"${cents // 100}.{cents % 100:02d}"


def _cents(cents: int) -> str:
    return "1 cent" if cents == 1 else f"{cents} cents"


def _expected_sentence(
    subject: str, reference: str, relation: str, magnitude: int, card_style: str
) -> str:
    if relation == "EQUAL_COST":
        return f"{subject} and {reference} have equal mean cost per parcel."
    if card_style == "DOLLARS":
        word = "more" if relation == "HIGHER_COST" else "less"
        return f"{subject} costs {_money(magnitude)} {word} per parcel than {reference}."
    word = "more expensive" if relation == "HIGHER_COST" else "cheaper"
    return f"{subject} is {_cents(magnitude)} {word} per parcel than {reference}."


# -- report -------------------------------------------------------------------


@dataclass
class Check:
    name: str
    passed: bool
    detail: str


@dataclass
class VerificationReport:
    checks: list[Check] = field(default_factory=list)
    derived: dict[str, Any] = field(default_factory=dict)
    hashes: dict[str, str] = field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return all(check.passed for check in self.checks)

    @property
    def failures(self) -> list[Check]:
        return [check for check in self.checks if not check.passed]

    def record(self, name: str, passed: bool, detail: str = "") -> None:
        self.checks.append(Check(name=name, passed=bool(passed), detail=detail))

    def as_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "derived": self.derived,
            "hashes": self.hashes,
            "checks": [
                {"name": c.name, "passed": c.passed, "detail": c.detail} for c in self.checks
            ],
        }


def verify_package(
    *,
    csv_path: Path,
    dataset_sha: str,
    memberships: list[list[Any]],
    comparison: dict[str, Any],
    documents: list[dict[str, Any]],
    occurrences: list[dict[str, Any]],
    decision: dict[str, Any],
    artifacts: dict[str, bytes],
    expected_hashes: dict[str, str] | None = None,
) -> VerificationReport:
    """Audit the real generated bytes against independently derived expectations."""
    report = VerificationReport()

    # 1. The raw measurements are what the release claims they are.
    raw = csv_path.read_bytes()
    report.record(
        "dataset_bytes_unchanged",
        hashlib.sha256(raw).hexdigest() == dataset_sha,
        f"recorded {dataset_sha}",
    )
    rows = list(csv.DictReader(raw.decode("utf-8").splitlines()))
    costs = {row["batch_id"]: int(row["cost_cents"]) for row in rows}
    report.record("dataset_row_count", len(rows) == len(costs) == len(memberships), f"{len(rows)} rows")

    # 2. The membership snapshot agrees with those immutable measurements.
    snapshot_costs_ok = all(
        batch_id in costs and costs[batch_id] == int(cost)
        for batch_id, _lane, cost in memberships
    )
    report.record("membership_costs_match_csv", snapshot_costs_ok)

    # 3. Re-aggregate from scratch.
    totals: dict[str, int] = {}
    counts: dict[str, int] = {}
    for batch_id, lane_id, _cost in memberships:
        totals[lane_id] = totals.get(lane_id, 0) + costs[batch_id]
        counts[lane_id] = counts.get(lane_id, 0) + 1

    left_id, right_id = comparison["left_lane_id"], comparison["right_lane_id"]
    left_mean = Fraction(totals.get(left_id, 0), max(counts.get(left_id, 0), 1))
    right_mean = Fraction(totals.get(right_id, 0), max(counts.get(right_id, 0), 1))
    difference = right_mean - left_mean
    if difference == 0:
        relation = "EQUAL_COST"
    else:
        relation = "HIGHER_COST" if difference > 0 else "LOWER_COST"
    magnitude = _round_half_up(abs(difference))

    report.derived = {
        "left": {
            "lane_id": left_id,
            "total_cents": totals.get(left_id, 0),
            "count": counts.get(left_id, 0),
            "mean_cents": str(left_mean),
        },
        "right": {
            "lane_id": right_id,
            "total_cents": totals.get(right_id, 0),
            "count": counts.get(right_id, 0),
            "mean_cents": str(right_mean),
        },
        "relation": relation,
        "magnitude_cents": magnitude,
    }

    report.record(
        "minimum_sample_satisfied",
        counts.get(left_id, 0) >= comparison["min_n"]
        and counts.get(right_id, 0) >= comparison["min_n"],
        f"{counts.get(left_id, 0)} vs {counts.get(right_id, 0)}, min {comparison['min_n']}",
    )

    subject = comparison["right_lane_name"]
    reference = comparison["left_lane_name"]

    # 4. Parse every issued document.
    by_document = {doc["document_id"]: doc for doc in documents}
    expected_occurrences: dict[str, list[dict[str, Any]]] = {}
    for occurrence in occurrences:
        expected_occurrences.setdefault(occurrence["document_id"], []).append(occurrence)

    report.record(
        "all_registered_documents_issued",
        set(artifacts) == set(by_document),
        f"issued {sorted(artifacts)}",
    )

    for document_id in sorted(by_document):
        body = artifacts.get(document_id)
        if body is None:
            report.record(f"{document_id}:present", False, "no bytes issued")
            continue
        digest = hashlib.sha256(body).hexdigest()
        report.hashes[document_id] = digest
        if expected_hashes is not None:
            report.record(
                f"{document_id}:hash_matches_approved",
                expected_hashes.get(document_id) == digest,
                f"actual {digest}",
            )

        blocks, meta = parse_document(body)
        found = {block.block_id: block for block in blocks}

        # 4a. Every registered occurrence appears as a complete card.
        wanted = expected_occurrences.get(document_id, [])
        finding_blocks = [b for b in blocks if b.kind == "finding"]
        report.record(
            f"{document_id}:registered_card_count",
            len(finding_blocks) == len(wanted),
            f"{len(finding_blocks)} rendered, {len(wanted)} registered",
        )

        for occurrence in wanted:
            block = found.get(occurrence["block_id"])
            if block is None or block.kind != "finding":
                report.record(f"{document_id}:{occurrence['block_id']}:card", False, "missing")
                continue
            style = occurrence["card_style"]
            expected_text = _expected_sentence(subject, reference, relation, magnitude, style)
            assertion = block.paragraphs[1] if len(block.paragraphs) > 1 else ""
            report.record(
                f"{document_id}:{occurrence['block_id']}:assertion",
                assertion == expected_text,
                f"found {assertion!r}, expected {expected_text!r}",
            )
            report.record(
                f"{document_id}:{occurrence['block_id']}:typed_relation",
                block.attrs.get("data-relation") == relation,
                f"found {block.attrs.get('data-relation')}",
            )
            report.record(
                f"{document_id}:{occurrence['block_id']}:typed_magnitude",
                block.attrs.get("data-magnitude-cents") == str(magnitude),
                f"found {block.attrs.get('data-magnitude-cents')}",
            )
            expected_unit = "USD_PER_PARCEL" if style == "DOLLARS" else "CENTS_PER_PARCEL"
            report.record(
                f"{document_id}:{occurrence['block_id']}:unit",
                block.attrs.get("data-unit") == expected_unit,
                f"found {block.attrs.get('data-unit')}",
            )
            report.record(
                f"{document_id}:{occurrence['block_id']}:occurrence_identity",
                block.attrs.get("data-occurrence-id") == occurrence["occurrence_id"],
            )
            # 4b. No superseded assertion survives anywhere in the file.
            for other_relation in ("HIGHER_COST", "LOWER_COST", "EQUAL_COST"):
                if other_relation == relation:
                    continue
                stale = _expected_sentence(
                    subject, reference, other_relation, magnitude, style
                )
                report.record(
                    f"{document_id}:{occurrence['block_id']}:no_{other_relation.lower()}",
                    stale.encode("utf-8") not in body,
                    "a contradicted assertion is still present",
                )

        # 4c. Unregistered narrative is byte-for-byte what the source says.
        for block_spec in by_document[document_id]["blocks"]:
            if block_spec["kind"] != "narrative":
                continue
            block = found.get(block_spec["id"])
            if block is None:
                report.record(f"{document_id}:{block_spec['id']}:narrative", False, "missing")
                continue
            expected = [" ".join(p.split()) for p in block_spec["paragraphs"]]
            actual = block.paragraphs[: len(expected)]
            report.record(
                f"{document_id}:{block_spec['id']}:narrative_unchanged",
                actual == expected,
                f"found {actual!r}",
            )
            report.record(
                f"{document_id}:{block_spec['id']}:scope_label",
                block.attrs.get("data-assessed") == "false",
                "narrative must be labelled unassessed",
            )

        # 4d. The typed decision block states the committed disposition.
        decision_blocks = [b for b in blocks if b.kind == "decision"]
        if any(b["kind"] == "decision" for b in by_document[document_id]["blocks"]):
            report.record(
                f"{document_id}:decision_block_present", len(decision_blocks) == 1
            )
            if decision_blocks:
                block = decision_blocks[0]
                report.record(
                    f"{document_id}:decision_status",
                    block.attrs.get("data-decision-status") == decision["expected_status"],
                    f"found {block.attrs.get('data-decision-status')}",
                )
                report.record(
                    f"{document_id}:decision_identity",
                    block.attrs.get("data-decision-id") == decision["decision_id"],
                )
        else:
            report.record(f"{document_id}:no_unexpected_decision_block", not decision_blocks)

        # 4e. Edition metadata ties the file to the evidence it was built from.
        report.record(
            f"{document_id}:dataset_metadata",
            meta.get("rr-dataset-sha") == dataset_sha,
            f"found {meta.get('rr-dataset-sha')}",
        )
        report.record(
            f"{document_id}:document_metadata",
            meta.get("rr-document-id") == document_id,
        )

    return report
