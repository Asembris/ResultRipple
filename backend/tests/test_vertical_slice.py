def test_impact_is_discovered_from_graph_relationships(seeded, ari: TestClient) -> None:
    """Both occurrences, their distinct owners, the proposal and its reviewer."""
    helpers.apply_correction(ari)
    graph = seeded["graph"]

    impacted = graph.impacted_occurrences(domain.CASE_ID)
    assert {row["occurrence_id"] for row in impacted} == {domain.OCC_OPS, domain.OCC_MEMO}
    assert {row["document_id"] for row in impacted} == {domain.DOC_OPS, domain.DOC_MEMO}

    state = helpers.workspace(ari)
    owners = {doc["document_id"]: doc["owner_id"] for doc in state["scope"]}
    assert owners == {domain.DOC_OPS: domain.PERSON_ARI, domain.DOC_MEMO: domain.PERSON_SAM}
    assert state["decision"]["basis_claim_id"] == domain.CLAIM_ID
    assert state["decision"]["current_reviewer_id"] == domain.PERSON_NOOR

    # Both registered uses are out of date, and by direction, not magnitude.
    assert len(state["assessment"]) == 2
    for entry in state["assessment"]:
        assert entry["relation_changed"] is True
        assert entry["magnitude_changed"] is False


